# === Proposed H&G formula (CH04 §4o) ====================================
# Replaces the original [50T, 60T]+probe-shift rule. Justified at all four
# thesis frequencies in the figures generated by this script — the snapped
# window lands firmly inside the eyeballed plateau at IN+OUT, per40+per240.
N_OFFSET_PERIODS = 15.0    # 5 (wavemaker ramp) + 10 (H&G "10 periods after arrival")
WINDOW_PERIODS   = 10.0    # H&G's 10T window
SNAP_HALFWIDTH_T = 1.0     # ±1 wave period UC search window for snap-to-start
TANK_DEPTH_M     = HG.TANK_DEPTH_M

# Matched x-axis for ALL rows (per40 and per240) so the reader compares them
# on the same time scale.
