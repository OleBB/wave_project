"""
H&G window fitness check — proposed-formula window overlaid on η(t)
====================================================================

For each thesis frequency (1.3, 1.4, 1.5, 1.6 Hz at 0.2 V), one figure
showing four representative runs — (per40 nowind, per40 fullwind,
per240 nowind, per240 fullwind) — at the IN probe (9373/170) and the
OUT probe (12400/250). The shaded green band is the H&G window from
the proposed formula:

    t_start = r / c_g(f, h) + N_OFFSET / f       (seconds)
    t_end   = t_start + 10 / f                   (10T length)

with N_OFFSET = 15 periods (= ~5 wavemaker-ramp + 10 H&G safety).
Start is snapped to the nearest zero-upcrossing within ±T (same as
the live pipeline). End = start + 10·samples_per_period (no separate
end-snap in this prototype — kept simple).

Visual purpose: confirm the window sits inside the wavetrain at every
thesis frequency for both per40 (paddle stops at 40/f s) and per240
(plenty of paddle-driven signal). x-axis matched at 0–50 s and y-axis
shared across all 8 panes so the cells stack on the same time + amplitude
scale.

Outputs (4 thesis figures + scratch mirrors):
    output/FIGURES/ch04_hg_per40_window_fitness_f13.{pdf}
    output/FIGURES/ch04_hg_per40_window_fitness_f14.{pdf}
    output/FIGURES/ch04_hg_per40_window_fitness_f15.{pdf}
    output/FIGURES/ch04_hg_per40_window_fitness_f16.{pdf}
    output/TEXFIGU/ch04_hg_per40_window_fitness_f{13,14,15,16}.tex
    analysis_scratch/hg_per40_window_fitness_f{13,14,15,16}.{pdf,png}

Run from repo root:
    /opt/anaconda3/envs/draumkvedet/bin/python analysis_scratch/hg_per40_window_fitness.py
"""

